  // ---------- Recorder ----------
  function newRec() { return { step: 0, role: null, anon: false, qs: [], ans: {}, secs: {}, voice: !!SR, live: false, t0: 0, done: false }; }
  function buildQs(role) {
    var qs = QUESTIONS[role].concat([UNIVERSAL]);
    var p = tools.filter(function (t) { return t.status === "piloting" && t.roles.indexOf(role) > -1; })[0];
    if (p) qs.push({ id: "loop", q: "You've been trying “" + p.name + "”. Has it helped? What's off?", tip: "Be blunt. This decides whether it ships, changes or gets cut.", loop: true });
    return qs;
  }
  var recog = null, tick = null;
  function accrue() { var q = rec.qs[rec.step - 1]; if (rec.t0 && q) rec.secs[q.id] = (rec.secs[q.id] || 0) + (Date.now() - rec.t0) / 1000; rec.t0 = 0; }
  function stopVoice() { if (recog) { recog.onend = null; try { recog.stop(); } catch (e) {} recog = null; } if (rec && rec.live) { rec.live = false; accrue(); } clearInterval(tick); }
  function runTimer(q) { clearInterval(tick); tick = setInterval(function () { var el = $("fr-timer"); if (el && rec.t0) el.textContent = dur((rec.secs[q.id] || 0) + (Date.now() - rec.t0) / 1000); }, 400); }

  function renderRecorder() {
    if (!rec) rec = newRec();
    var total = rec.qs.length, h;
    if (rec.done) {
      root.innerHTML = '<div class="fr-rec"><div class="card"><div><h3>Thanks. Your report is in.</h3><p class="lede">We’ll group what everyone said, share what we heard, and build against the biggest problems first. Next cycle asks whether it helped.</p></div><div class="fr-navrow"><button class="fr-btn" id="fr-again">Record another</button><button class="fr-btn primary" data-go="reports">See it in Reports</button></div></div></div>';
      $("fr-again").addEventListener("click", function () { rec = newRec(); renderRecorder(); }); wireGo(); return;
    }
    if (rec.step === 0) {
      root.innerHTML = '<div class="fr-rec"><div class="card"><div><h3>Tell us what slows you down</h3><p class="lede">You know the process, the tools and the customers better than anyone. Answer four quick questions out loud, about three minutes. Say as much or as little as you want. We use this to cut busywork and get you better prepped for calls.</p></div>' +
        '<div class="fr-label">Your role</div><div class="fr-roles" role="group" aria-label="Your role">' + Object.keys(ROLES).map(function (k) { return '<button type="button" class="fr-role" data-role="' + k + '" aria-pressed="' + (rec.role === k) + '"><b>' + ROLES[k].label + "</b><span>" + ROLES[k].blurb + "</span></button>"; }).join("") + "</div>" +
        '<label class="fr-check"><input type="checkbox" id="fr-anon"' + (rec.anon ? " checked" : "") + "> Submit without my name</label>" +
        '<div class="fr-navrow"><span class="meta">' + (SR ? "Uses your microphone. Your browser will ask first." : "Your browser can’t transcribe live, so you’ll use keyboard dictation.") + '</span><button class="fr-btn primary" id="fr-start"' + (rec.role ? "" : " disabled") + ">Start</button></div></div></div>";
      root.querySelectorAll("[data-role]").forEach(function (b) { b.addEventListener("click", function () { rec.role = b.getAttribute("data-role"); renderRecorder(); }); });
      $("fr-anon").addEventListener("change", function (e) { rec.anon = e.target.checked; });
      $("fr-start").addEventListener("click", function () { rec.qs = buildQs(rec.role); rec.step = 1; renderRecorder(); });
      return;
    }
    if (rec.step > total) {
      var all_ = Object.keys(rec.secs).reduce(function (a, k) { return a + rec.secs[k]; }, 0);
      root.innerHTML = '<div class="fr-rec"><div class="card"><div class="fr-progress">' + rec.qs.map(function () { return '<i class="done"></i>'; }).join("") + '</div><div><h3>Look it over</h3><p class="lede">' + dur(all_) + ' of talking. Fix anything the transcript got wrong, then send.</p></div><div class="fr-review">' +
        rec.qs.map(function (q, i) { return '<div class="item"><div class="fr-label">Question ' + (i + 1) + '</div><div style="font-weight:600;margin-top:2px">' + esc(q.q) + "</div><p>" + (rec.ans[q.id] ? esc(rec.ans[q.id]) : '<span class="meta">Skipped</span>') + '</p><button class="fr-btn ghost sm" data-edit="' + (i + 1) + '">Edit</button></div>'; }).join("") +
        '</div><div class="fr-navrow"><button class="fr-btn" id="fr-back">Back</button><button class="fr-btn primary" id="fr-send">Send report</button></div></div></div>';
      root.querySelectorAll("[data-edit]").forEach(function (b) { b.addEventListener("click", function () { rec.step = +b.getAttribute("data-edit"); renderRecorder(); }); });
      $("fr-back").addEventListener("click", function () { rec.step = total; renderRecorder(); });
      $("fr-send").addEventListener("click", submit);
      return;
    }
    var q = rec.qs[rec.step - 1];
    h = '<div class="fr-rec"><div class="card"><div class="fr-progress" aria-label="Question ' + rec.step + " of " + total + '">' + rec.qs.map(function (_, i) { return '<i class="' + (i < rec.step - 1 ? "done" : i === rec.step - 1 ? "cur" : "") + '"></i>'; }).join("") + "</div>" +
      '<div style="display:flex;flex-direction:column;gap:8px"><span class="fr-label">Question ' + rec.step + " of " + total + (q.loop ? " · Closing the loop" : "") + '</span><div class="fr-q">' + esc(q.q) + '</div><p class="fr-tip">' + esc(q.tip) + "</p></div>";
    if (rec.voice) {
      h += '<div class="fr-microw"><button class="fr-mic' + (rec.live ? " live" : "") + '" id="fr-mic" type="button" aria-label="' + (rec.live ? "Stop" : "Start talking") + '">' +
        (rec.live ? '<svg viewBox="0 0 24 24"><rect x="6" y="6" width="12" height="12" rx="2"/></svg>' : '<svg viewBox="0 0 24 24"><rect x="9" y="3" width="6" height="11" rx="3"/><path d="M5 11a7 7 0 0 0 14 0M12 18v3"/></svg>') +
        '</button><div><div class="fr-timer" id="fr-timer">' + dur(rec.secs[q.id]) + '</div><div class="fr-status">' + (rec.live ? "Listening. Talk naturally, tap to stop." : rec.ans[q.id] ? "Tap to keep talking." : "Tap and start talking.") + "</div></div></div>";
    } else {
      h += '<div class="fr-note"><b>Talk instead of typing.</b> Tap the box, then tap the microphone on your keyboard (on a Mac, press Fn twice) and talk. Your words land in the box as you speak.</div>';
    }
    h += '<label class="fr-label" for="fr-ans">Transcript' + (rec.voice ? " · edit if anything’s off" : "") + '</label><textarea class="fr-ta" id="fr-ans" placeholder="' + (rec.voice ? "Your words show up here as you talk." : "Tap here, then the mic on your keyboard.") + '">' + esc(rec.ans[q.id] || "") + "</textarea>" +
      (rec.voice ? "" : '<div class="fr-timer" id="fr-timer" style="font-size:14px;color:var(--muted)">' + dur(rec.secs[q.id]) + "</div>") +
      '<div class="fr-navrow"><button class="fr-btn" id="fr-prev">' + (rec.step === 1 ? "Change role" : "Back") + '</button><div><button class="fr-btn ghost" id="fr-skip">Skip</button><button class="fr-btn primary" id="fr-next">' + (rec.step === total ? "Review" : "Next question") + "</button></div></div></div></div>";
    root.innerHTML = h;
    var ta = $("fr-ans");
    ta.addEventListener("input", function () { rec.ans[q.id] = ta.value; });
    if (!rec.voice) {
      ta.addEventListener("focus", function () { rec.t0 = Date.now(); runTimer(q); });
      ta.addEventListener("blur", function () { accrue(); clearInterval(tick); });
    }
    function go(n) { if (!rec.voice && rec.t0) accrue(); stopVoice(); rec.ans[q.id] = ta.value.trim(); rec.step = n; renderRecorder(); }
    $("fr-next").addEventListener("click", function () { go(rec.step + 1); });
    $("fr-skip").addEventListener("click", function () { ta.value = ""; go(rec.step + 1); });
    $("fr-prev").addEventListener("click", function () { go(rec.step - 1); });
    if (rec.voice) $("fr-mic").addEventListener("click", function () { if (rec.live) { stopVoice(); rec.ans[q.id] = ta.value; renderRecorder(); } else startVoice(q); });
  }

  function startVoice(q) {
    try { recog = new SR(); recog.continuous = true; recog.interimResults = true; recog.lang = navigator.language || "en-US"; }
    catch (e) { rec.voice = false; renderRecorder(); return; }
    var base = (rec.ans[q.id] || "").trim(), finals = "";
    recog.onresult = function (e) {
      var interim = "";
      for (var i = e.resultIndex; i < e.results.length; i++) { var r = e.results[i]; if (r.isFinal) finals += r[0].transcript.trim() + " "; else interim += r[0].transcript; }
      var ta = $("fr-ans"); var kept = [base, finals.trim()].filter(Boolean).join(" ");
      if (ta) ta.value = [kept, interim.trim()].filter(Boolean).join(" ");
      rec.ans[q.id] = kept;
    };
    recog.onerror = function (e) {
      if (e.error === "not-allowed" || e.error === "service-not-allowed" || e.error === "audio-capture") {
        stopVoice(); rec.voice = false; renderRecorder();
        var n = root.querySelector(".fr-note"); if (n) n.insertAdjacentHTML("afterbegin", "<b>The mic is blocked in this browser.</b> ");
      }
    };
    recog.onend = function () { if (rec.live) { base = [base, finals.trim()].filter(Boolean).join(" "); finals = ""; try { recog.start(); } catch (e) {} } };
    try { recog.start(); } catch (e) { rec.voice = false; renderRecorder(); return; }
    rec.live = true; rec.t0 = Date.now(); renderRecorder(); runTimer(q);
  }

  function submit() {
    mine.unshift({ role: rec.role, displayName: rec.anon ? "Anonymous" : "You", mine: true, submittedAt: new Date().toISOString(),
      answers: rec.qs.map(function (q) { return { question: q.q, text: (rec.ans[q.id] || "").trim(), seconds: Math.round(rec.secs[q.id] || 0) }; }) });
    save(); rec.done = true; renderRecorder(); var c = $("fr-count"); if (c) c.textContent = all().length;
  }

  render();
